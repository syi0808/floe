import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { nextEnabled, matchingOption } from '../src/components/ui/selection-navigation.js';

const options = [{ value: 'personal', label: 'Personal' }, { value: 'holidays', label: 'Holidays', disabled: true }, { value: 'project', label: 'Project' }, { value: 'work', label: 'Work' }];
assert.equal(nextEnabled(options, -1, 1), 0);
assert.equal(nextEnabled(options, 0, 1), 2);
assert.equal(nextEnabled(options, 2, -1), 0);
assert.equal(nextEnabled(options, 3, 1), 0);
assert.equal(nextEnabled(options, 0, -1), 3);
assert.equal(nextEnabled([], -1, 1), -1);
assert.equal(nextEnabled([{ disabled: true }], 0, 1), -1);
assert.equal(matchingOption(options, 'w', 0), 3);
assert.equal(matchingOption(options, 'P', 0), 2);
assert.equal(matchingOption(options, 'p', 2), 0);
assert.equal(matchingOption(options, 'Pro', 0), 2);
assert.equal(matchingOption(options, 'h', 0), 0);
assert.equal(matchingOption(options, 'missing', 2), 2);
const source = await readFile(new URL('../src/components/ui/Select.jsx', import.meta.url), 'utf8');
const styles = await readFile(new URL('../src/components/ui/selection-popover.css', import.meta.url), 'utf8');
assert(source.includes('aria-activedescendant='));
assert(source.includes("role={menu ? 'menu' : 'listbox'}"));
assert(source.includes('aria-selected={!menu ? value === option.value : undefined}'));
assert(source.includes("trigger.current?.closest('dialog') || document.body"));
assert(source.includes("event.key === 'Escape'"));
assert(source.includes("event.key === 'Tab'"));
assert(source.includes('if (!options[index] || options[index].disabled) return;'));
assert(styles.includes('prefers-reduced-motion: reduce'));
assert(styles.includes('forced-colors: active'));
assert(styles.includes('transform-origin: bottom left'));
assert(styles.includes('min-height: 44px'));
console.log('Selection controls: 13 navigation assertions and 11 semantic/motion source guards passed.');
